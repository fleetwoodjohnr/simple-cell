// Independent check: every formula from the function test table is also calculated by LibreOffice Calc, and the
// three answers (Simple Cell, LibreOffice, the expected value from Microsoft's documentation) are compared.
// Run with `npm run crosscheck` (needs LibreOffice). Writes docs/LIBREOFFICE_CROSSCHECK.md.
import { describe, expect, it } from 'vitest'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { book } from './helpers/book'
import { CASES, DATA } from './functions/cases'

const enabled = process.env.LO_CROSSCHECK === '1'
const soffice = ['/usr/bin/soffice', '/usr/lib/libreoffice/program/soffice', '/Applications/LibreOffice.app/Contents/MacOS/soffice', 'C:\\Program Files\\LibreOffice\\program\\soffice.exe'].find((p) => existsSync(p))

const COL = 51 // AZ: where the formulas go (away from the data)

function colName(c: number) {
  let s = ''
  for (let n = c + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s
  return s
}

function near(a: unknown, b: unknown) {
  // LibreOffice writes logical values to CSV as 1 and 0.
  if (typeof a === 'boolean' && typeof b === 'number') return Number(a) === b
  if (typeof b === 'boolean' && typeof a === 'number') return Number(b) === a
  if (typeof a === 'number' && typeof b === 'number') return a === b || Math.abs(a - b) <= Math.max(1e-9, Math.abs(b) * 1e-7)
  if (typeof a === 'boolean' || typeof b === 'boolean') return String(a).toUpperCase() === String(b).toUpperCase()
  return String(a ?? '') === String(b ?? '')
}

describe.skipIf(!enabled || !soffice)('LibreOffice cross-check', () => {
  it('compares every test formula with LibreOffice Calc', () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'sc-lo-'))
    const cases = Object.entries(CASES).flatMap(([fn, list]) => list.map(([f, want]) => ({ fn, f, want })))
    // Grid: DATA in place, then one formula per row in column AZ.
    const rows: string[][] = []
    const put = (r: number, c: number, v: string) => {
      while (rows.length <= r) rows.push([])
      while (rows[r].length <= c) rows[r].push('')
      rows[r][c] = v
    }
    for (const [ref, v] of Object.entries(DATA)) {
      const m = /^([A-Z]+)(\d+)$/.exec(ref)!
      let c = 0
      for (const ch of m[1]) c = c * 26 + ch.charCodeAt(0) - 64
      const text = typeof v === 'string' && v.startsWith("'") ? `="${v.slice(1)}"` : v === 'TRUE' ? '=TRUE()' : String(v)
      put(Number(m[2]) - 1, c - 1, text)
    }
    cases.forEach((k, i) => put(i, COL, '=' + k.f))
    const csv = rows.map((r) => r.map((v) => `"${v.replace(/"/g, '""')}"`).join(',')).join('\n') + '\n'
    writeFileSync(path.join(dir, 'cases.csv'), csv)
    execFileSync(soffice!, ['--headless', '--norestore', `-env:UserInstallation=${pathToFileURL(path.join(dir, 'profile')).href}`, '--infilter=CSV:44,34,76,1,,1033,false,true,false,false,false,-1,true', '--convert-to', 'csv:Text - txt - csv (StarCalc):44,34,76,1,,1033,false,true,false,false,false,-1', '--outdir', path.join(dir, 'out'), path.join(dir, 'cases.csv')], { timeout: 180_000 })
    const outFile = readdirSync(path.join(dir, 'out')).find((f) => f.endsWith('.csv'))!
    const out = readFileSync(path.join(dir, 'out', outFile), 'utf8')
    const parsed = parseCsv(out)
    const b = book(DATA)
    const lines: string[] = []
    let agree = 0
    let loOnlyRight = 0
    let scOnlyRight = 0
    let neither = 0
    const rowsOut: string[] = []
    cases.forEach((k, i) => {
      const lo = coerce(parsed[i]?.[COL] ?? '')
      const sc = b.calc(k.f)
      const same = near(sc, lo)
      const scOk = near(sc, k.want) || (typeof k.want === 'number' && typeof sc === 'number' && Math.abs(sc - k.want) <= Math.abs(k.want) * 1e-5)
      const loOk = near(lo, k.want) || (typeof k.want === 'number' && typeof lo === 'number' && Math.abs(lo - k.want) <= Math.abs(k.want) * 1e-5)
      if (same) agree++
      else {
        if (scOk && !loOk) scOnlyRight++
        else if (loOk && !scOk) loOnlyRight++
        else if (!scOk && !loOk) neither++
        rowsOut.push(`| ${k.fn} | \`=${k.f.replace(/\|/g, '\\|')}\` | ${fmt(sc)} | ${fmt(lo)} | ${fmt(k.want)} | ${scOk ? 'Simple Cell' : loOk ? 'LibreOffice' : '—'} |`)
      }
    })
    lines.push('# LibreOffice cross-check', '')
    lines.push(`_Generated by \`npm run crosscheck\` with ${execFileSync(soffice!, ['--version'], { encoding: 'utf8' }).trim()}._`, '')
    lines.push('Every formula in the function test table (`tests/unit/functions/cases.ts`) is calculated by Simple Cell and by LibreOffice Calc. The expected value comes from Microsoft’s documentation examples where available.')
    lines.push('LibreOffice is an independent implementation, but it is not Excel. Where the two disagree, the last column says which one matches the expected (Excel) value. Many LibreOffice differences come from it treating unentered array formulas as legacy implicit-intersection formulas, or from functions it lacks.', '')
    lines.push(`| | Formulas |`, `|---|---|`, `| Same result | ${agree} |`, `| Different, Simple Cell matches Excel’s value | ${scOnlyRight} |`, `| Different, LibreOffice matches Excel’s value | ${loOnlyRight} |`, `| Different, neither matches | ${neither} |`, `| Total | ${cases.length} |`, '')
    if (rowsOut.length) lines.push('## Differences', '', '| Function | Formula | Simple Cell | LibreOffice | Expected | Matches Excel |', '|---|---|---|---|---|---|', ...rowsOut, '')
    writeFileSync(path.join(import.meta.dirname, '../../docs/LIBREOFFICE_CROSSCHECK.md'), lines.join('\n'))
    // The suite fails if LibreOffice is right and Simple Cell is not: that is a bug to fix.
    expect(loOnlyRight, rowsOut.filter((r) => r.endsWith('| LibreOffice |')).join('\n')).toBe(0)
  }, 240_000)
})

function fmt(v: unknown) {
  if (v === null || v === undefined || v === '') return '(empty)'
  return String(typeof v === 'number' ? Number(v.toPrecision(12)) : v).replace(/\|/g, '\\|')
}

function coerce(s: string): unknown {
  if (s === '') return null
  if (s === 'TRUE' || s === 'FALSE') return s === 'TRUE'
  if (/^-?\d+(\.\d+)?(E[+-]?\d+)?$/i.test(s)) return Number(s)
  if (/^#/.test(s) && /[!?A]$/.test(s)) return s.replace(/^Err:\d+$/, '#VALUE!')
  if (/^Err:\d+$/.test(s)) return '#VALUE!'
  return s
}

function parseCsv(text: string): string[][] {
  const rows: string[][] = []
  let row: string[] = []
  let f = ''
  let q = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (q) {
      if (c === '"' && text[i + 1] === '"') {
        f += '"'
        i++
      } else if (c === '"') q = false
      else f += c
    } else if (c === '"') q = true
    else if (c === ',') {
      row.push(f)
      f = ''
    } else if (c === '\n') {
      row.push(f)
      rows.push(row)
      row = []
      f = ''
    } else if (c !== '\r') f += c
  }
  if (f || row.length) {
    row.push(f)
    rows.push(row)
  }
  return rows
}
