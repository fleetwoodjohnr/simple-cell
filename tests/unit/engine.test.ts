import { describe, expect, it } from 'vitest'
import { book } from './helpers/book'

describe('recalculation', () => {
  it('recalculates dependents when a value changes', () => {
    const b = book({ A1: 2, A2: '=A1*10', A3: '=A2+A1', B1: '=SUM(A1:A3)' })
    expect(b.get('A3')).toBe(22)
    expect(b.get('B1')).toBe(44)
    b.set('A1', 3)
    expect(b.get('A2')).toBe(30)
    expect(b.get('A3')).toBe(33)
    expect(b.get('B1')).toBe(66)
  })
  it('handles long chains without stack overflow', () => {
    const b = book({ A1: 1 })
    for (let i = 2; i <= 5000; i++) b.doc.input(b.sheet, i - 1, 0, `=A${i - 1}+1`)
    expect(b.get('A5000')).toBe(5000)
    b.set('A1', 10)
    expect(b.get('A5000')).toBe(5009)
  })
  it('detects circular references (value 0, flagged)', () => {
    const b = book({ A1: '=B1+1', B1: '=A1+1' })
    expect(b.doc.engine.circular.size).toBeGreaterThan(0)
    expect(typeof b.get('A1')).toBe('number')
  })
  it('iterates circular references when enabled', () => {
    const b = book()
    b.doc.wb.calc.iterate = true
    b.set('A1', '=B1/2+1')
    b.set('B1', '=A1')
    expect(b.get('A1') as number).toBeCloseTo(2, 2)
  })
  it('spills arrays and reports #SPILL! when blocked', () => {
    const b = book({ A1: '=SEQUENCE(3)' })
    expect([b.get('A1'), b.get('A2'), b.get('A3')]).toEqual([1, 2, 3])
    b.set('B1', '=SUM(A1#)')
    expect(b.get('B1')).toBe(6)
    b.set('A3', 'x')
    expect(b.get('A1')).toBe('#SPILL!')
    expect(b.get('A2')).toBe(null)
    b.set('A3', '')
    expect(b.get('A1')).toBe(1)
    expect(b.get('A3')).toBe(3)
    b.set('A1', '=SEQUENCE(4)')
    expect(b.get('A4')).toBe(4)
    expect(b.get('B1')).toBe(10)
  })
  it('undo and redo', () => {
    const b = book({ A1: 1, B1: '=A1*2' })
    b.set('A1', 5)
    expect(b.get('B1')).toBe(10)
    b.doc.undo()
    expect(b.get('A1')).toBe(1)
    expect(b.get('B1')).toBe(2)
    b.doc.redo()
    expect(b.get('B1')).toBe(10)
  })
  it('names and LET/LAMBDA', () => {
    const b = book({ A1: 4 })
    b.doc.defineName('Rate', '=Sheet1!$A$1')
    expect(b.calc('Rate*2')).toBe(8)
    b.set('A1', 5)
    b.set('B2', '=Rate+1')
    expect(b.get('B2')).toBe(6)
    expect(b.calc('LET(x,2,y,x*3,x+y)')).toBe(8)
    expect(b.calc('LAMBDA(a,b,a*b)(3,4)')).toBe(12)
    b.doc.defineName('Double', '=LAMBDA(n,n*2)')
    expect(b.calc('Double(21)')).toBe(42)
    expect(b.calc('MAP(SEQUENCE(3),LAMBDA(x,x*x))')).toBe(1)
    expect(b.calc('SUM(MAP(SEQUENCE(3),LAMBDA(x,x*x)))')).toBe(14)
    expect(b.calc('REDUCE(0,SEQUENCE(4),LAMBDA(a,v,a+v))')).toBe(10)
  })
  it('insert and delete rows adjust references', () => {
    const b = book({ A1: 1, A2: 2, A3: 3, B1: '=SUM(A1:A3)', C1: '=A3' })
    b.doc.insertRows(b.sheet, 1, 2)
    expect(b.formula('B1')).toBe('=SUM(A1:A5)')
    expect(b.formula('C1')).toBe('=A5')
    expect(b.get('A5')).toBe(3)
    b.doc.deleteRows(b.sheet, 4, 1)
    expect(b.formula('C1')).toBe('=#REF!')
    expect(b.get('C1')).toBe('#REF!')
    b.doc.undo()
    expect(b.formula('C1')).toBe('=A5')
    b.doc.undo()
    expect(b.formula('B1')).toBe('=SUM(A1:A3)')
    expect(b.get('B1')).toBe(6)
  })
  it('cross-sheet references and sheet rename', () => {
    const b = book({ A1: 7 })
    const id = b.doc.addSheet('Data')
    b.doc.input(id, 0, 0, '=Sheet1!A1*2')
    expect(b.doc.value(id, 0, 0)).toBe(14)
    b.doc.renameSheet(b.sheet, 'Main')
    expect(b.doc.formulaText(id, 0, 0)).toBe('=Main!A1*2')
    b.set('A1', 8)
    expect(b.doc.value(id, 0, 0)).toBe(16)
  })
  it('volatile functions and INDIRECT', () => {
    const b = book({ A1: 3, B1: 'A1' })
    b.set('C1', '=INDIRECT(B1)*2')
    expect(b.get('C1')).toBe(6)
    b.set('A1', 4)
    expect(b.get('C1')).toBe(8)
    b.set('D1', '=OFFSET(A1,0,0)+1')
    expect(b.get('D1')).toBe(5)
  })
  it('keeps typed formats', () => {
    const b = book({ A1: '$1,234.50', A2: '25%', A3: '1/15/2024', A4: "'007" })
    expect(b.get('A1')).toBe(1234.5)
    expect(b.text('A1')).toBe('$1,234.50 ')
    expect(b.get('A2')).toBe(0.25)
    expect(b.text('A2')).toBe('25%')
    expect(b.text('A3')).toBe('1/15/2024')
    expect(b.get('A4')).toBe('007')
  })
})

describe('insert and delete cells (shift)', () => {
  it('moves only the band of cells and adjusts references the way Excel does', async () => {
    const { book } = await import('./helpers/book')
    const b = book({ A1: 1, B1: 10, B2: 20, B3: 30, C1: 100, C3: 300, E1: '=SUM(B1:B3)', E2: '=B3', E3: '=SUM(A1:C3)', E4: '=C3' })
    b.doc.insertCells({ sheet: b.sheet, r0: 1, c0: 1, r1: 1, c1: 1 }, 'down') // B2, shift down
    expect([b.get('B2'), b.get('B3'), b.get('B4')]).toEqual([null, 20, 30])
    expect(b.get('C3')).toBe(300) // other columns stay
    expect(b.doc.formulaText(b.sheet, 0, 4)).toBe('=SUM(B1:B4)') // a range inside the band grows
    expect(b.doc.formulaText(b.sheet, 1, 4)).toBe('=B4') // a reference to a moved cell follows it
    expect(b.doc.formulaText(b.sheet, 2, 4)).toBe('=SUM(A1:C3)') // wider ranges stay
    expect(b.doc.formulaText(b.sheet, 3, 4)).toBe('=C3')
    b.doc.undo()
    expect(b.doc.formulaText(b.sheet, 0, 4)).toBe('=SUM(B1:B3)')
    b.doc.deleteCells({ sheet: b.sheet, r0: 0, c0: 1, r1: 0, c1: 1 }, 'up') // B1, shift up
    expect([b.get('B1'), b.get('B2')]).toEqual([20, 30])
    expect(b.doc.formulaText(b.sheet, 0, 4)).toBe('=SUM(B1:B2)')
    expect(b.get('E1')).toBe(50)
    b.doc.undo()
    b.doc.insertCells({ sheet: b.sheet, r0: 0, c0: 0, r1: 1, c1: 0 }, 'right') // A1:A2, shift right
    expect([b.get('A1'), b.get('B1'), b.get('C1'), b.get('D1')]).toEqual([null, 1, 10, 100])
    expect(b.get('B3')).toBe(30) // row 3 is outside the band
    b.doc.merge({ sheet: b.sheet, r0: 5, c0: 0, r1: 5, c1: 2 })
    expect(() => b.doc.insertCells({ sheet: b.sheet, r0: 4, c0: 1, r1: 4, c1: 1 }, 'down')).toThrow(/merged/)
  })
})

describe('paste special', () => {
  it('values, formats, operations, skip blanks, transpose, column widths, notes', async () => {
    const { book } = await import('./helpers/book')
    const b = book({ A1: 1, A2: 2, B1: '=A1*10', D1: 100, D2: 'x', D3: '=5' })
    const s = b.sheet
    b.doc.format([{ sheet: s, r0: 0, c0: 0, r1: 1, c1: 1 }], { bold: true, numFmt: '0.00', borderTop: { style: 'thin' } })
    const A = (r0: number, c0: number, r1 = r0, c1 = c0) => ({ sheet: s, r0, c0, r1, c1 })
    b.doc.pasteSpecial(A(0, 0, 1, 1), A(5, 0), { what: 'values' })
    expect([b.get('A6'), b.get('B6'), b.doc.formulaText(s, 5, 1)]).toEqual([1, 10, null])
    expect(b.doc.styleAt(s, 5, 0).bold).toBeUndefined()
    b.doc.pasteSpecial(A(0, 0, 1, 1), A(5, 0), { what: 'formats' })
    expect(b.doc.styleAt(s, 5, 0)).toMatchObject({ bold: true, numFmt: '0.00' })
    expect(b.get('A6')).toBe(1)
    b.doc.pasteSpecial(A(0, 0), A(7, 0), { what: 'allExceptBorders' })
    expect(b.doc.styleAt(s, 7, 0)).toMatchObject({ bold: true })
    expect(b.doc.styleAt(s, 7, 0).borderTop).toBeUndefined()
    // Multiply D1:D3 by A2 (2): numbers and formulas change, text stays.
    b.doc.pasteSpecial(A(1, 0), A(0, 3, 2, 3), { what: 'values', op: 'multiply' })
    expect([b.get('D1'), b.get('D2'), b.get('D3')]).toEqual([200, 'x', 10])
    expect(b.doc.formulaText(s, 2, 3)).toBe('=(5)*2')
    // Skip blanks: the empty C1 doesn't overwrite.
    b.set('F1', 'keep')
    b.doc.pasteSpecial(A(0, 2), A(0, 5), { what: 'all', skipBlanks: true })
    expect(b.get('F1')).toBe('keep')
    // Transpose a column into a row; the formula's references keep their offsets.
    b.doc.pasteSpecial(A(0, 0, 1, 1), A(10, 0), { what: 'all', transpose: true })
    expect([b.get('A11'), b.get('B11'), b.get('A12')]).toEqual([1, 2, 10])
    b.doc.setColWidths(s, [0], 150)
    b.doc.pasteSpecial(A(0, 0), A(0, 7), { what: 'colWidths' })
    expect(b.doc.wb.sheets[0].colWidth(7)).toBe(150)
    b.doc.setNote(s, 0, 0, 'hello', 'me')
    b.doc.pasteSpecial(A(0, 0), A(20, 0), { what: 'notes' })
    expect(b.doc.noteAt(s, 20, 0)?.text).toBe('hello')
    expect(b.get('A21')).toBeNull()
  })
})

describe('go to special', () => {
  it('blanks, constants and formulas by type, notes, visible cells, last cell', async () => {
    const { book } = await import('./helpers/book')
    const b = book({ A1: 1, B1: 'x', C1: '=A1*2', A2: '=1/0', C2: 'TRUE', A3: 5, C3: 7 })
    const s = b.sheet
    const names = (areas: { r0: number; c0: number; r1: number; c1: number }[]) => areas.map((a) => (a.r0 === a.r1 && a.c0 === a.c1 ? `${'ABC'[a.c0]}${a.r0 + 1}` : `${'ABC'[a.c0]}${a.r0 + 1}:${'ABC'[a.c1]}${a.r1 + 1}`))
    const one = [{ sheet: s, r0: 0, c0: 0, r1: 0, c1: 0 }]
    expect(names(b.doc.goToSpecial(s, one, 'blanks'))).toEqual(['B2:B3'])
    expect(names(b.doc.goToSpecial(s, one, 'constants', 'n'))).toEqual(['A1', 'A3', 'C3'])
    expect(names(b.doc.goToSpecial(s, one, 'constants', 't'))).toEqual(['B1'])
    expect(names(b.doc.goToSpecial(s, one, 'constants', 'l'))).toEqual(['C2'])
    expect(names(b.doc.goToSpecial(s, one, 'formulas'))).toEqual(['C1', 'A2'])
    expect(names(b.doc.goToSpecial(s, one, 'formulas', 'e'))).toEqual(['A2'])
    expect(names(b.doc.goToSpecial(s, one, 'lastCell'))).toEqual(['C3'])
    b.doc.hide(s, 'row', [1], true)
    expect(names(b.doc.goToSpecial(s, [{ sheet: s, r0: 0, c0: 0, r1: 2, c1: 2 }], 'visible'))).toEqual(['A1:C1', 'A3:C3'])
    b.doc.setNote(s, 2, 1, 'n')
    expect(names(b.doc.goToSpecial(s, one, 'notes'))).toEqual(['B3'])
    expect(() => b.doc.goToSpecial(s, one, 'validation')).toThrow(/No cells/)
  })
})
