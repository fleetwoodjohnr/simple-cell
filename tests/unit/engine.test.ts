import { describe, expect, it } from 'vitest'
import { book } from './helpers/book'

describe('recalculation', () => {
  it('recalculates dependents when a value changes', () => {
    const b = book({ A1: 2, A2: '=A1*10', A3: '=A2+A1', B1: '=SUM(A1:A3)' })
    expect(b.get('A3')).toBe(22)
    expect(b.get('B1')).toBe(44)
    b.set('A1', 3)
    expect(b.get('A2')).toBe(30)
    expect(b.get('A3')).toBe(33)
    expect(b.get('B1')).toBe(66)
  })
  it('handles long chains without stack overflow', () => {
    const b = book({ A1: 1 })
    for (let i = 2; i <= 5000; i++) b.doc.input(b.sheet, i - 1, 0, `=A${i - 1}+1`)
    expect(b.get('A5000')).toBe(5000)
    b.set('A1', 10)
    expect(b.get('A5000')).toBe(5009)
  })
  it('detects circular references (value 0, flagged)', () => {
    const b = book({ A1: '=B1+1', B1: '=A1+1' })
    expect(b.doc.engine.circular.size).toBeGreaterThan(0)
    expect(typeof b.get('A1')).toBe('number')
  })
  it('iterates circular references when enabled', () => {
    const b = book()
    b.doc.wb.calc.iterate = true
    b.set('A1', '=B1/2+1')
    b.set('B1', '=A1')
    expect(b.get('A1') as number).toBeCloseTo(2, 2)
  })
  it('spills arrays and reports #SPILL! when blocked', () => {
    const b = book({ A1: '=SEQUENCE(3)' })
    expect([b.get('A1'), b.get('A2'), b.get('A3')]).toEqual([1, 2, 3])
    b.set('B1', '=SUM(A1#)')
    expect(b.get('B1')).toBe(6)
    b.set('A3', 'x')
    expect(b.get('A1')).toBe('#SPILL!')
    expect(b.get('A2')).toBe(null)
    b.set('A3', '')
    expect(b.get('A1')).toBe(1)
    expect(b.get('A3')).toBe(3)
    b.set('A1', '=SEQUENCE(4)')
    expect(b.get('A4')).toBe(4)
    expect(b.get('B1')).toBe(10)
  })
  it('undo and redo', () => {
    const b = book({ A1: 1, B1: '=A1*2' })
    b.set('A1', 5)
    expect(b.get('B1')).toBe(10)
    b.doc.undo()
    expect(b.get('A1')).toBe(1)
    expect(b.get('B1')).toBe(2)
    b.doc.redo()
    expect(b.get('B1')).toBe(10)
  })
  it('names and LET/LAMBDA', () => {
    const b = book({ A1: 4 })
    b.doc.defineName('Rate', '=Sheet1!$A$1')
    expect(b.calc('Rate*2')).toBe(8)
    b.set('A1', 5)
    b.set('B2', '=Rate+1')
    expect(b.get('B2')).toBe(6)
    expect(b.calc('LET(x,2,y,x*3,x+y)')).toBe(8)
    expect(b.calc('LAMBDA(a,b,a*b)(3,4)')).toBe(12)
    b.doc.defineName('Double', '=LAMBDA(n,n*2)')
    expect(b.calc('Double(21)')).toBe(42)
    expect(b.calc('MAP(SEQUENCE(3),LAMBDA(x,x*x))')).toBe(1)
    expect(b.calc('SUM(MAP(SEQUENCE(3),LAMBDA(x,x*x)))')).toBe(14)
    expect(b.calc('REDUCE(0,SEQUENCE(4),LAMBDA(a,v,a+v))')).toBe(10)
  })
  it('insert and delete rows adjust references', () => {
    const b = book({ A1: 1, A2: 2, A3: 3, B1: '=SUM(A1:A3)', C1: '=A3' })
    b.doc.insertRows(b.sheet, 1, 2)
    expect(b.formula('B1')).toBe('=SUM(A1:A5)')
    expect(b.formula('C1')).toBe('=A5')
    expect(b.get('A5')).toBe(3)
    b.doc.deleteRows(b.sheet, 4, 1)
    expect(b.formula('C1')).toBe('=#REF!')
    expect(b.get('C1')).toBe('#REF!')
    b.doc.undo()
    expect(b.formula('C1')).toBe('=A5')
    b.doc.undo()
    expect(b.formula('B1')).toBe('=SUM(A1:A3)')
    expect(b.get('B1')).toBe(6)
  })
  it('cross-sheet references and sheet rename', () => {
    const b = book({ A1: 7 })
    const id = b.doc.addSheet('Data')
    b.doc.input(id, 0, 0, '=Sheet1!A1*2')
    expect(b.doc.value(id, 0, 0)).toBe(14)
    b.doc.renameSheet(b.sheet, 'Main')
    expect(b.doc.formulaText(id, 0, 0)).toBe('=Main!A1*2')
    b.set('A1', 8)
    expect(b.doc.value(id, 0, 0)).toBe(16)
  })
  it('volatile functions and INDIRECT', () => {
    const b = book({ A1: 3, B1: 'A1' })
    b.set('C1', '=INDIRECT(B1)*2')
    expect(b.get('C1')).toBe(6)
    b.set('A1', 4)
    expect(b.get('C1')).toBe(8)
    b.set('D1', '=OFFSET(A1,0,0)+1')
    expect(b.get('D1')).toBe(5)
  })
  it('keeps typed formats', () => {
    const b = book({ A1: '$1,234.50', A2: '25%', A3: '1/15/2024', A4: "'007" })
    expect(b.get('A1')).toBe(1234.5)
    expect(b.text('A1')).toBe('$1,234.50 ')
    expect(b.get('A2')).toBe(0.25)
    expect(b.text('A2')).toBe('25%')
    expect(b.text('A3')).toBe('1/15/2024')
    expect(b.get('A4')).toBe('007')
  })
})
